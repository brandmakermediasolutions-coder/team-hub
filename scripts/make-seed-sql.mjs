// Builds supabase/seed.sql from src/store/seed.js so the shared database starts
// with the same team, clients and current work as the demo.
// Run: node scripts/make-seed-sql.mjs
import { writeFileSync } from 'node:fs'
import { buildSeed } from '../src/store/seed.js'

const snake = (s) => s.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`)
const str = (v) => `'${String(v).replace(/'/g, "''")}'`
const lit = (v) => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean' || typeof v === 'number') return String(v)
  if (Array.isArray(v) && v.some((x) => x && typeof x === 'object')) return `${str(JSON.stringify(v))}::jsonb`
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`
  return str(v)
}
const insert = (table, rows) => {
  if (!rows.length) return ''
  const cols = Object.keys(rows[0])
  return `insert into ${table} (${cols.map(snake).join(', ')}) values\n${rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')}\non conflict (id) do nothing;\n\n`
}

const d = buildSeed()
const sql = `-- Team Hub · starting data (generated by scripts/make-seed-sql.mjs — do not edit by hand)
-- Run after schema.sql. Safe to re-run: rows that already exist are left alone.

${insert('employees', d.employees)}${insert('clients', d.clients)}${insert('tasks', d.tasks)}${insert('comments', d.comments)}${insert('updates', d.updates)}${insert('posts', d.posts)}${insert('activity', d.activity)}${insert('repeat_rules', d.rules)}${insert('task_templates', d.templates)}`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log('wrote supabase/seed.sql')
